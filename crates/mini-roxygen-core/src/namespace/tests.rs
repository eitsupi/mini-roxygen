#[test]
fn unresolved_s3_warning_has_exact_contract_and_binding_span() {
    let output = namespace(
        r#"#' @export
`unknown.class` <- function(x) x
"#,
    );
    let diagnostic = output
        .diagnostics
        .iter()
        .find(|diagnostic| diagnostic.code == DiagnosticCode::UnresolvedS3Export)
        .expect("unresolved S3 warning");
    assert_eq!(diagnostic.severity, Severity::Warning);
    assert_eq!(diagnostic.code.as_str(), "unresolved-s3-export");
    assert_eq!(
        diagnostic.message,
        "cannot distinguish unknown.class as an S3 method from a plain dotted function without evaluating R"
    );
    assert_eq!(
        diagnostic.help.as_deref(),
        Some(
            "add @method <generic> <class> before the bare @export, or replace it with @exportS3Method <generic> <class>"
        )
    );
    assert_eq!(
        diagnostic.primary.message,
        "automatic S3 classification is unresolved"
    );
    assert_eq!(diagnostic.primary.span.range, TextRange::new(11, 26));
    assert_eq!(
        output
            .diagnostics
            .iter()
            .filter(|diagnostic| diagnostic.code == DiagnosticCode::UnresolvedS3Export)
            .count(),
        1
    );
    assert_eq!(
        output.content,
        "# Generated by mini-roxygen (roxygen2 compatible): do not edit by hand\n\n"
    );
}
