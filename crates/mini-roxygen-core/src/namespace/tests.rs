#[test]
fn typed_import_self_import_filtering_covers_both_decision_dimensions() {
    let cases = [
        ("no package, external", None, "external"),
        ("no package, current", None, "current"),
        ("package, external", Some("current"), "external"),
        ("package, current", Some("current"), "current"),
    ];
    let mut rendered = String::new();

    for (label, current_package, package) in cases {
        let source = format!(
            r#"#' @import {package}
NULL
#' @importFrom {package} self_name
NULL
"#
        );
        let output = namespace_with_package(&source, current_package);
        let codes = output
            .diagnostics
            .iter()
            .map(|diagnostic| diagnostic.code)
            .collect::<Vec<_>>();
        let is_self_import = current_package == Some("current") && package == "current";
        let expected_codes = if is_self_import {
            vec![DiagnosticCode::SelfImport, DiagnosticCode::SelfImport]
        } else {
            Vec::new()
        };
        assert_eq!(codes, expected_codes, "diagnostic codes for {label}");

        if is_self_import {
            let diagnostics = output.diagnostics.iter().collect::<Vec<_>>();
            assert_eq!(diagnostics[0].primary.span.range, TextRange::new(11, 18));
            assert_eq!(diagnostics[1].primary.span.range, TextRange::new(39, 46));
        }

        rendered.push_str(label);
        rendered.push('\n');
        rendered.push_str(&output.content);
    }

    insta::assert_snapshot!(rendered, @"
    no package, external
    # Generated by mini-roxygen (roxygen2 compatible): do not edit by hand

    import(external)
    importFrom(external,self_name)
    no package, current
    # Generated by mini-roxygen (roxygen2 compatible): do not edit by hand

    import(current)
    importFrom(current,self_name)
    package, external
    # Generated by mini-roxygen (roxygen2 compatible): do not edit by hand

    import(external)
    importFrom(external,self_name)
    package, current
    # Generated by mini-roxygen (roxygen2 compatible): do not edit by hand
    ");
}

