fn namespace(text: &str) -> super::NamespaceBuildOutput {
    namespace_with_package(text, None)
}

fn namespace_with_package(
    text: &str,
    current_package: Option<&str>,
) -> super::NamespaceBuildOutput {
    build_namespace(&model(text).package, current_package)
}

fn namespace_files(files: &[(&str, &str)]) -> super::NamespaceBuildOutput {
    namespace_files_with_collate(files, false)
}

fn namespace_files_with_collate(
    files: &[(&str, &str)],
    collate: bool,
) -> super::NamespaceBuildOutput {
    let (package, sources) = package_files_with_collate(files, collate);
    build_namespace_with_sources(&package, &sources, None)
}

fn package_files_with_collate(
    files: &[(&str, &str)],
    collate: bool,
) -> (crate::model::PackageModel, SourceMap) {
    let mut sources = SourceMap::new();
    let mut all_blocks = Vec::new();
    let mut all_bindings = Vec::new();
    for (path, text) in files {
        let source = SourceFile::new((*path).into(), (*text).to_owned());
        let file = sources.add_file(source.clone());
        let index = build_object_index(crate::arity_adapter::parse(&source, file), file);
        all_bindings.extend(index.bindings.iter().cloned());
        let parsed = crate::arity_adapter::parse(&source, file);
        for object in index.documented {
            let raw = parsed
                .top_level
                .iter()
                .find_map(|entry| {
                    entry
                        .documentation
                        .as_ref()
                        .filter(|block| block.id == object.block)
                })
                .expect("indexed object has documentation");
            let (tags, diagnostics) = crate::tags::parse_block(
                &source,
                raw,
                &TagParseOptions::default().with_unknown_tags(UnknownTagPolicy::Ignore),
            );
            assert!(diagnostics.is_empty());
            all_blocks.push(DocumentedBlock {
                block: BlockRef {
                    file,
                    block: object.block,
                },
                block_span: object.block_span,
                target: object.target,
                tags,
            });
        }
    }
    let package = if collate {
        let metadata = PackageMetadata::new("example", None)
            .expect("valid package metadata")
            .with_collate_directive();
        build_package_model_with_metadata_and_bindings(
            &sources,
            all_blocks,
            &metadata,
            all_bindings,
        )
        .package
    } else {
        build_package_model_with_bindings(&sources, all_blocks, all_bindings).package
    };
    (package, sources)
}

