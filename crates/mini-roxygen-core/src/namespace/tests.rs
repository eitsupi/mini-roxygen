#[test]
fn the_null_s3_method_form_emits_nothing_and_says_nothing() {
    // A method registered at load time, by an s3_register() call in .onLoad,
    // must not appear in NAMESPACE. Emitting nothing is the whole behaviour;
    // a diagnostic here would reject documentation that is already correct.
    let output = namespace(
        r#"#' @exportS3Method NULL
f <- function() NULL
"#,
    );
    assert_eq!(
        output.content,
        "# Generated by mini-roxygen (roxygen2 compatible): do not edit by hand\n\n"
    );
    assert!(output.diagnostics.is_empty());
}

#[test]
fn the_null_s3_method_form_does_not_depend_on_recognizing_the_object() {
    // The tag says "no directive" on its own. A method built at run time has
    // no statically recognizable function assignment, and that is exactly the
    // case load-time registration exists for, so it must not be rejected.
    for source in [
        "#' @exportS3Method NULL\nmake_method()\n",
        "#' @exportS3Method NULL\nNULL\n",
        "#' @exportS3Method NULL\nnot_a_function <- 1\n",
    ] {
        let output = namespace(source);
        assert_eq!(
            output.content,
            "# Generated by mini-roxygen (roxygen2 compatible): do not edit by hand\n\n",
            "unexpected content for {source:?}"
        );
        assert!(
            output.diagnostics.is_empty(),
            "unexpected diagnostics for {source:?}"
        );
    }
}

#[test]
fn identical_s3_lines_from_different_quoting_routes_collapse_to_one() {
    // The auto-quoted and literal routes are kept apart so each renders the
    // way its originating tag demands, but two directives that render the
    // same text are the same registration. Deduplicating on the route instead
    // of the rendered spelling emitted the line twice.
    let output = namespace(
        r#"#' @method print foo
#' @export
print.foo <- function(x, ...) x
#' @exportS3Method print foo
NULL
"#,
    );
    assert_eq!(output.content.matches("S3method(print,foo)").count(), 1);
}

#[test]
fn identical_s3_lines_from_comma_bearing_literals_collapse_to_one() {
    // A literal argument may contain a comma, so splitting the key across the
    // two arguments is not injective over the rendered line: `a,b` plus `c`
    // and `a` plus `b,c` both render S3method(a,b,c).
    let output = namespace(
        r#"#' @exportS3Method a,b c
NULL
#' @exportS3Method a b,c
NULL
"#,
    );
    assert_eq!(output.content.matches("S3method(a,b,c)").count(), 1);
}

